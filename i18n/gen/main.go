package main

import (
	"bytes"
	"crypto/sha1"
	"encoding/base32"
	"log"
	"os"
	"path/filepath"
	"runtime"
	"slices"
	"strings"
	"text/template"

	"github.com/goccy/go-yaml"
	"github.com/gosimple/slug"
)

type groupItem struct {
	Name string
	Key  string
}

type groupData struct {
	Name  string
	Items []groupItem
}

func main() {
	_, filename, _, ok := runtime.Caller(0)
	if !ok {
		log.Fatalf("Failed to get current file information")
	}
	sourceDir := filepath.Dir(filename)
	err := os.Chdir(sourceDir)
	if err != nil {
		log.Fatalf("Failed to change directory to %s: %v", sourceDir, err)
	}

	type LangData struct {
		EN string `yaml:"EN"`
		DE string `yaml:"DE"`
	}

	var keys []string
	langData := make(map[string]LangData)
	var groups []groupData

	dataFiles, err := filepath.Glob("../data/*.yaml")
	if err != nil || len(dataFiles) == 0 {
		log.Fatalf("No YAML data files found in ../data/")
	}

	for _, yFile := range dataFiles {
		groupName := exportGroupName(yFile)

		yamlFile, err := os.ReadFile(yFile)
		if err != nil {
			log.Fatalf("Error reading YAML file %s: %v", yFile, err)
		}

		var ll []LangData
		if err := yaml.Unmarshal(yamlFile, &ll); err != nil {
			log.Fatalf("error reading in lang config from %s: %v", yFile, err)
		}

		g := groupData{Name: groupName}

		for _, l := range ll {
			key := sl(l.EN)

			if slices.Contains(keys, key) {
				log.Fatalf("Key '%s' already exists in the lang config (from file %s, EN: %q)", key, yFile, l.EN)
			}

			keys = append(keys, key)
			langData[key] = LangData{EN: l.EN, DE: l.DE}
			g.Items = append(g.Items, groupItem{
				Name: exportName(key),
				Key:  key,
			})
		}

		groups = append(groups, g)
	}

	const keyTempl = `// Code generated by go generate; DO NOT EDIT.
// This file was generated by a tool from data.yaml

package i18n

const(
{{range $i, $item := .}}{{if eq $i 0}}	{{$item}} int = iota{{else}}	{{$item}}{{end}}
{{end}})
`
	tmpl, err := template.New("keys").Parse(keyTempl)
	if err != nil {
		log.Fatalf("Error parsing keys template: %v", err)
	}

	var buf bytes.Buffer
	err = tmpl.Execute(&buf, keys)
	if err != nil {
		log.Fatalf("Error executing keys template: %v", err)
	}

	outputFile := "../keys.go"
	err = os.WriteFile(outputFile, buf.Bytes(), 0644)
	if err != nil {
		log.Fatalf("Error writing output key file: %v", err)
	}

	const valTempl = `// Code generated by go generate; DO NOT EDIT.
// This file was generated by a tool from data.yaml

package i18n

var (
	LangMap = map[int]Data{
{{- range $key, $value := . }}
		{{ $key }}:  {LangKey: "{{$key}}", LangData: LangData{EN: "{{$value.EN}}", DE: "{{$value.DE}}"}},
{{- end }}
	}
)
`
	tmpl, err = template.New("vals").Parse(valTempl)
	if err != nil {
		log.Fatalf("Error parsing val template: %v", err)
	}

	var bufVal bytes.Buffer
	err = tmpl.Execute(&bufVal, langData)
	if err != nil {
		log.Fatalf("Error executing vals template: %v", err)
	}

	outputFile = "../vals.go"
	err = os.WriteFile(outputFile, bufVal.Bytes(), 0644)
	if err != nil {
		log.Fatalf("Error writing output val file: %v", err)
	}

	const lTempl = `// Code generated by go generate; DO NOT EDIT.
// This file was generated by a tool from data.yaml

package i18n

var L = struct {
{{- range . }}
	{{ .Name }} struct {
		{{- range .Items }}
		{{ .Name }} int
		{{- end }}
	}
{{- end }}
}{
{{- range . }}
	{{ .Name }}: struct {
		{{- range .Items }}
		{{ .Name }} int
		{{- end }}
	}{
		{{- range .Items }}
		{{ .Name }}: {{ .Key }},
		{{- end }}
	},
{{- end }}
}
`
	tmpl, err = template.New("l").Parse(lTempl)
	if err != nil {
		log.Fatalf("Error parsing l template: %v", err)
	}

	var bufL bytes.Buffer
	err = tmpl.Execute(&bufL, groups)
	if err != nil {
		log.Fatalf("Error executing l template: %v", err)
	}

	outputFile = "../l.go"
	err = os.WriteFile(outputFile, bufL.Bytes(), 0644)
	if err != nil {
		log.Fatalf("Error writing output l file: %v", err)
	}
}

func exportGroupName(filePath string) string {
	base := strings.TrimSuffix(filepath.Base(filePath), filepath.Ext(filePath))
	if base == "" {
		return "General"
	}
	return strings.ToUpper(base[:1]) + base[1:]
}

func exportName(key string) string {
	key = strings.TrimPrefix(key, "LK_")
	parts := strings.Split(key, "_")
	for i, p := range parts {
		if p == "" {
			continue
		}
		parts[i] = strings.ToUpper(p[:1]) + p[1:]
	}
	return strings.Join(parts, "")
}

func sl(s string) string {
	const (
		maxLen   = 50
		prefix   = "LK_"
		hashLen  = 8
		sep      = "_"
		fallback = "key"
	)

	base := strings.ReplaceAll(slug.Make(s), "-", "_")
	if base == "" {
		base = fallback
	}
	if base[0] >= '0' && base[0] <= '9' {
		base = "k_" + base
	}

	plain := prefix + base
	if len(plain) <= maxLen {
		return plain
	}

	sum := sha1.Sum([]byte(s))
	hash := base32.StdEncoding.WithPadding(base32.NoPadding).EncodeToString(sum[:])
	hash = strings.ToLower(hash)
	if len(hash) > hashLen {
		hash = hash[:hashLen]
	}

	reserved := len(sep) + len(hash)
	availBase := maxLen - len(prefix) - reserved
	if availBase < 1 {
		availBase = 1
	}
	if len(base) > availBase {
		base = strings.Trim(base[:availBase], "_")
		if base == "" {
			base = fallback
		}
	}

	return prefix + base + sep + hash
}
